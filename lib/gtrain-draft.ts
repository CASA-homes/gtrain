/** A player's G-Train draft picks across seasons (latest first), matched on full name. */
export function gtrainPicksFor(name: string): (GTrainPick & { year: number })[] {
  const key = name.replace(/\+$/, '').toLowerCase();
  return Object.entries(GTRAIN_DRAFTS).flatMap(([y, ps]) => ps.filter((p) => p.name.toLowerCase() === key).map((p) => ({ ...p, year: Number(y) })))
    .sort((a, b) => b.year - a.year);
}

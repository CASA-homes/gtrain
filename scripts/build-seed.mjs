// Builds supabase/seed.sql from the scraped Keeper data in /data.
// Usage: npm run seed
import { readFileSync, writeFileSync } from 'node:fs';

const league = JSON.parse(readFileSync(new URL('../data/league.json', import.meta.url)));
const squadsTxt = readFileSync(new URL('../data/squads-2026.txt', import.meta.url), 'utf8');

const SEASON = 2026;
const SHORT = {
  'Bodega Boys': 'BB', 'Serong So’Right': 'SS', "Muzza's Murabito's": 'MM', 'Such Is Fyfe': 'SF',
  "Pato's Fantasy Team": 'PF', 'NSW-ACT Academy': 'NA', 'A Brayshaw Thing': 'AB',
  'Fo’ Sheezel my Neezel': 'FS', 'Bito’s Boys': 'BI', 'Ram Dawgs': 'RD',
};
const POS_LONG = { D: 'DEF', M: 'MID', R: 'RUC', F: 'FWD' };

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === '-' || v === '' || v === undefined ? 'null' : Number(v));
const arr = (xs) => `array[${xs.map(q).join(',')}]::text[]`;
const intArr = (xs) => `array[${xs.map((x) => (x === '-' ? 'null' : Number(x))).join(',')}]::int[]`;

const teamIdSql = (name) => `(select id from public.teams where name = ${q(name)})`;

const out = [];
out.push('-- Generated by scripts/build-seed.mjs. Do not edit by hand.');
out.push('begin;');

// Teams
for (const t of league.teams) {
  out.push(`insert into public.teams (keeper_id, name, coach_name, short_code, joined_season) values (${t.keeper_id}, ${q(t.name)}, ${q(t.coach)}, ${q(SHORT[t.name])}, 2022);`);
}

// Seasons and honour roll
for (const h of league.honour_roll) {
  const isGf = h.year === 2026;
  out.push(`insert into public.seasons (year, premier_id, runner_up_id, spoon_id, medal, gf_winner_score, gf_loser_score) values (${h.year}, ${teamIdSql(h.premier)}, ${teamIdSql(h.runner_up)}, ${teamIdSql(h.spoon)}, ${q(h.medal)}, ${isGf ? league.grand_final_2026.winner_score : 'null'}, ${isGf ? league.grand_final_2026.loser_score : 'null'});`);
}

// 2026 ladder
for (const l of league.ladder_2026_final) {
  const [w, lo, d] = l.wl.split('-').map(Number);
  out.push(`insert into public.ladder (season, team_id, rank, wins, losses, draws, points, pts_for, pts_against) values (${SEASON}, ${teamIdSql(l.team)}, ${l.rank}, ${w}, ${lo}, ${d}, ${l.pts}, ${l.for}, ${l.against});`);
}

// Players, 2026 stats and current squads
let team = null;
let count = 0;
for (const raw of squadsTxt.split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('# ')) continue;
  if (line.startsWith('## ')) { team = line.slice(3).split(' | ')[0]; continue; }
  const [name, posRaw, status, games, avg, ...last5] = line.split('|');
  const positions = posRaw.includes('/') && posRaw.length <= 5 && /^[DMRF](\/[DMRF])+$/.test(posRaw)
    ? posRaw.split('/').map((p) => POS_LONG[p])
    : posRaw.split('/').filter(Boolean);
  const pid = `(select id from public.players where name = ${q(name)} and positions = ${arr(positions)})`;
  out.push(`insert into public.players (name, positions) values (${q(name)}, ${arr(positions)});`);
  out.push(`insert into public.player_seasons (player_id, season, games, average, last5, tons, status) values (${pid}, ${SEASON}, ${num(games)}, ${num(avg)}, ${intArr(last5)}, null, ${q(status || null)});`);
  out.push(`insert into public.squad (player_id, team_id) values (${pid}, ${teamIdSql(team)});`);
  count++;
}

// Bodega Boys draft picks (other teams' picks get added when the feed runs)
const bb = teamIdSql('Bodega Boys');
for (const [year, list] of Object.entries(league.bodega_boys_picks)) {
  for (const p of list) {
    const m = p.match(/^R(\d+)(?: #(\d+))?(?: \(via (.+?)\))?( \(optional\))?$/);
    if (!m) throw new Error('Bad pick: ' + p);
    const [, round, overall, via, optional] = m;
    out.push(`insert into public.picks (year, round, overall, original_team_id, owner_team_id, is_optional) values (${year}, ${round}, ${overall ?? 'null'}, ${via ? teamIdSql(via) : bb}, ${bb}, ${optional ? 'true' : 'false'});`);
  }
}

out.push('commit;');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql written: ${league.teams.length} teams, ${count} players`);

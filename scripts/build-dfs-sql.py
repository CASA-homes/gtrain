"""data/dfs-2026.json + data/draft-picks.txt -> supabase/dfs-2026.sql"""
import json
d = json.load(open('data/dfs-2026.json'))
picks = {}
for l in open('data/draft-picks.txt'):
    if l.startswith('#'): continue
    y, p, n = l.strip().split('|'); picks[n.lower()] = (int(y), int(p))
q = lambda v: 'null' if v is None else "'" + str(v).replace("'", "''") + "'"
i = lambda v: 'null' if v is None else str(int(v))
rows = []
for x in d:
    pk = picks.get((x['full'] or '').lower())
    dy = pk[0] if pk else x['draft_year']
    rows.append(f"({q(x['team'])},{q(x['name'])},{q(x['full'])},{q(x['dob'])}::date,{i(dy)},{i(pk[1]) if pk else 'null'},{q(x['dfs_id'])},{i(x['height'])},{i(x['debut'])},{i(x['career_games'])},{q(json.dumps(x['hist']))}::jsonb,{q(json.dumps(x['box'])) if x['box'] else 'null'}::jsonb)")
vals = ',\n'.join(rows)
sql = f"""-- DFS Australia import, {len(rows)} players. Generated by scripts/build-dfs-sql.py
begin;
create temp table dfs (team text, name text, full_name text, dob date, draft_year int, draft_pick int, dfs_id text, height int, debut int, cg int, hist jsonb, box jsonb) on commit drop;
insert into dfs values
{vals};

update public.players p set full_name = d.full_name, birth_date = d.dob, draft_year = d.draft_year, draft_pick = d.draft_pick,
  dfs_id = d.dfs_id, height_cm = d.height, debut_year = d.debut, career_games = d.cg, hist = d.hist
from dfs d join public.teams t on t.name = d.team join public.squad s on s.team_id = t.id
where s.player_id = p.id and p.name = d.name;

update public.player_seasons ps set box = d.box
from dfs d join public.teams t on t.name = d.team join public.squad s on s.team_id = t.id join public.players p on p.id = s.player_id and p.name = d.name
where ps.player_id = p.id and ps.season = 2026;

select count(*) filter (where dfs_id is not null) as with_dfs, count(*) filter (where birth_date is not null) as with_dob, count(*) as total from public.players;
commit;
"""
open('supabase/dfs-2026.sql', 'w').write(sql)
print(len(rows), 'rows,', len(sql), 'chars')

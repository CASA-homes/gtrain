  select distinct on (np.full_name, np.club) np.*, p.id, p.positions::text[] old
    from np join players p on lower(p.full_name) = lower(np.full_name)
   where p.afl_club = np.club or (select count(*) from players q where lower(q.full_name) = lower(np.full_name)) = 1
   order by np.full_name, np.club, (p.afl_club = np.club) desc
), u as (
  update players p set positions = m.pos from m where p.id = m.id and not (m.old @> m.pos and m.pos @> m.old) returning p.id
)
